    [Fact]
    public void Reproduce_the_old_calculator_for_every_seeded_class_and_level()
    {
        using var database = SqliteDatabase.World();
        using WorldDbContext context = database.CreateDbContext();
        var rows = context.ClassLevelStats.AsNoTracking().ToList();
        var factors =
            context.ClassStatFactors.AsNoTracking().ToList().ToDictionary(f => f.Class);
        CombatFormula formula = context.CombatFormulas.AsNoTracking().Single();

        var expected = s_expected
            .Select(line => line.Split(','))
            .ToDictionary(f => (Enum.Parse<CharacterClass>(f[0]), ushort.Parse(f[1]), f[2] == "1"), f => string.Join(",", f.Skip(3)));

        Assert.Equal(rows.Count * 2, expected.Count);

        foreach (ClassLevelStat row in rows)
        {
            foreach (bool geared in new[] { false, true })
            {
                DerivedCharacterStats s = CharacterStatsCalculator.Calculate(row, geared ? s_gear : [], factors[row.Class], formula);
                string actual = string.Join(",", s.MaxHealth, s.MaxPower, s.Stamina, s.Strength, s.Agility, s.Intellect,
                    s.Armor, BitConverter.SingleToInt32Bits(s.BlockPct), s.Evasion, s.MaxWard,
                    BitConverter.SingleToInt32Bits(s.CritPct), s.AttackDamage, s.AbilityDamage);

                Assert.True(expected.TryGetValue((row.Class, row.Level, geared), out string? want),
                    $"no recorded output for {row.Class} level {row.Level}");
                Assert.True(want == actual, $"{row.Class} level {row.Level} geared={geared}: expected {want}, got {actual}");
            }
        }
    }
