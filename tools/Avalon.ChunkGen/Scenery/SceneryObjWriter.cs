using System.Globalization;
using System.Text;
using Polygon = System.Collections.Generic.IReadOnlyList<(float X, float Y, float Z)>;

namespace Avalon.ChunkGen;

/// <summary>
/// Writes a scenery piece's terrain as piece-local OBJ (x/z 0-30, y up) in the subset the client's vendor script reads:
/// "o", "v", "f" (triangles) and "usemtl" lines, plus comments, LF line ends, numbers invariant with at most 3
/// decimals and never "-0", so a rerun is byte-identical. Nothing bakes it: scenery is never walkable.
/// </summary>
public static class SceneryObjWriter
{
    /// <summary>
    /// <c>o Ground</c>, every grid vertex once (SceneryTerrain.Step apart), then one <c>usemtl</c> group per material
    /// that has faces, in SceneryTerrain.Palette order, each quad (one Step square) split along its (x0, z0)-(x1, z1)
    /// diagonal and each triangle wearing the material at its centroid; then each wall as <c>o Wall_&lt;n&gt;</c> and
    /// each surface with faces in the cell as <c>o Surface_&lt;n&gt;</c>, each under its material. Ground and surface
    /// triangles are wound so (b - a) x (c - a) points up. Refuses (InvalidOperationException naming the piece) a
    /// material outside the palette and a height that is not a number.
    /// </summary>
    public static string Write(SceneryPiece piece)
    {
        var text = new StringBuilder();
        text.Append("# Avalon scenery: ").Append(piece.Name).Append('\n');
        text.Append("# Generated by tools/Avalon.ChunkGen; regenerate it rather than editing it by hand\n");
        int written = 0;
        Ground(piece, text, ref written);

        int n = 1;
        foreach (SceneryWall wall in piece.Terrain.Walls)
        {
            CheckMaterial(piece, wall.Material, "a wall");
            (IReadOnlyList<(float X, float Y, float Z)> vertices, IReadOnlyList<(int A, int B, int C)> triangles) = Mesh(piece, wall);
            text.Append("o Wall_").Append(n++).Append('\n').Append("usemtl ").Append(wall.Material).Append('\n');
            foreach ((float x, float y, float z) in vertices)
                Vertex(text, x, y, z);
            foreach ((int a, int b, int c) in triangles)
                Face(text, written + a, written + b, written + c);
            written += vertices.Count;
        }

        n = 1;
        foreach (ScenerySurface surface in piece.Terrain.Surfaces)
        {
            CheckMaterial(piece, surface.Material, "a surface");
            if (Surface(surface.Within(0f, 0f, ChunkPiece.CellSize, ChunkPiece.CellSize)) is not { } mesh) continue;
            text.Append("o Surface_").Append(n++).Append('\n').Append("usemtl ").Append(surface.Material).Append('\n');
            foreach (string vertex in mesh.Vertices)
                text.Append("v ").Append(vertex).Append('\n');
            foreach ((int a, int b, int c) in mesh.Triangles)
                Face(text, written + a, written + b, written + c);
            written += mesh.Vertices.Count;
        }

        return text.ToString();
    }

    private static void Ground(SceneryPiece piece, StringBuilder text, ref int written)
    {
        int cells = (int)MathF.Round(ChunkPiece.CellSize / SceneryTerrain.Step);
        int side = cells + 1;
        text.Append("o Ground\n");
        for (int i = 0; i <= cells; i++)
        {
            for (int j = 0; j <= cells; j++)
            {
                float x = i * SceneryTerrain.Step, z = j * SceneryTerrain.Step, y = piece.Terrain.Height(x, z);
                if (!float.IsFinite(y))
                {
                    throw new InvalidOperationException(
                        $"{piece.Name}: the ground at ({ForestText.N(x)}, {ForestText.N(z)}) has height {ForestText.N(y)}, not a number");
                }
                Vertex(text, x, y, z);
            }
        }

        // Vertex (i, j) at (i * Step, j * Step) is i * side + j. Over the quad (x0, z0)-(x1, z1) the triangles
        // (x0z0, x1z1, x1z0) and (x0z0, x0z1, x1z1) have (b - a) x (c - a) pointing up whatever the heights.
        var groups = new Dictionary<string, List<(int A, int B, int C)>>(StringComparer.Ordinal);
        for (int i = 0; i < cells; i++)
        {
            for (int j = 0; j < cells; j++)
            {
                int v00 = i * side + j, v01 = v00 + 1, v10 = v00 + side, v11 = v10 + 1;
                float x0 = i * SceneryTerrain.Step, z0 = j * SceneryTerrain.Step, s = SceneryTerrain.Step;
                Add(groups, Material(piece, x0 + s * 2f / 3f, z0 + s / 3f), (v00, v11, v10));
                Add(groups, Material(piece, x0 + s / 3f, z0 + s * 2f / 3f), (v00, v01, v11));
            }
        }

        foreach (string material in SceneryTerrain.Palette)
        {
            if (!groups.TryGetValue(material, out List<(int A, int B, int C)>? faces)) continue;
            text.Append("usemtl ").Append(material).Append('\n');
            foreach ((int a, int b, int c) in faces)
                Face(text, a, b, c);
        }
        written = side * side;
    }

    private static string Material(SceneryPiece piece, float x, float z)
    {
        string material = piece.Terrain.Material(x, z);
        CheckMaterial(piece, material, $"the ground at ({ForestText.N(x)}, {ForestText.N(z)})");
        return material;
    }

    private static void CheckMaterial(SceneryPiece piece, string material, string what)
    {
        if (!SceneryTerrain.Palette.Contains(material, StringComparer.Ordinal))
            throw new InvalidOperationException($"{piece.Name}: {what} wears '{material}', which is not in the scenery palette");
    }

    private static (IReadOnlyList<(float X, float Y, float Z)>, IReadOnlyList<(int A, int B, int C)>) Mesh(SceneryPiece piece, SceneryWall wall)
    {
        try
        {
            return wall.Mesh();
        }
        catch (InvalidOperationException e)
        {
            throw new InvalidOperationException($"{piece.Name}: {e.Message}", e);
        }
    }

    private static void Add(Dictionary<string, List<(int A, int B, int C)>> groups, string material, (int, int, int) face)
    {
        if (!groups.TryGetValue(material, out List<(int A, int B, int C)>? faces))
            groups[material] = faces = [];
        faces.Add(face);
    }

    /// <summary>
    /// The polygons fanned into triangles over their written (rounded) vertices, each shared vertex once, each triangle
    /// turned to face up and one that is edge-on once rounded left out; null when no triangle is left.
    /// </summary>
    private static (List<string> Vertices, List<(int A, int B, int C)> Triangles)? Surface(IReadOnlyList<Polygon> polygons)
    {
        var index = new Dictionary<string, int>(StringComparer.Ordinal);
        var positions = new List<(double X, double Y, double Z)>();
        var vertices = new List<string>();
        var triangles = new List<(int A, int B, int C)>();
        foreach (Polygon polygon in polygons)
        {
            for (int k = 1; k + 1 < polygon.Count; k++)
            {
                int a = Index(polygon[0]), b = Index(polygon[k]), c = Index(polygon[k + 1]);
                (double X, double Y, double Z) pa = positions[a], pb = positions[b], pc = positions[c];
                double up = (pb.Z - pa.Z) * (pc.X - pa.X) - (pb.X - pa.X) * (pc.Z - pa.Z);
                if (up > 0) triangles.Add((a, b, c));
                else if (up < 0) triangles.Add((a, c, b));
            }
        }
        if (triangles.Count == 0) return null;

        // Only the vertices a kept triangle uses are written, renumbered in first use.
        var used = new Dictionary<int, int>();
        var kept = new List<string>();
        List<(int A, int B, int C)> renumbered = [.. triangles.Select(t => (Renumber(t.A), Renumber(t.B), Renumber(t.C)))];
        return (kept, renumbered);

        int Renumber(int v)
        {
            if (!used.TryGetValue(v, out int n))
            {
                used[v] = n = kept.Count;
                kept.Add(vertices[v]);
            }
            return n;
        }

        int Index((float X, float Y, float Z) p)
        {
            string key = $"{F(p.X)} {F(p.Y)} {F(p.Z)}";
            if (!index.TryGetValue(key, out int i))
            {
                index[key] = i = vertices.Count;
                vertices.Add(key);
                positions.Add((Rounded(p.X), Rounded(p.Y), Rounded(p.Z)));
            }
            return i;
        }
    }

    private static void Vertex(StringBuilder text, float x, float y, float z) =>
        text.Append("v ").Append(F(x)).Append(' ').Append(F(y)).Append(' ').Append(F(z)).Append('\n');

    /// <summary>A triangle over 0-based vertex numbers, written 1-based.</summary>
    private static void Face(StringBuilder text, int a, int b, int c) =>
        text.Append("f ").Append(a + 1).Append(' ').Append(b + 1).Append(' ').Append(c + 1).Append('\n');

    private static double Rounded(float value)
    {
        double rounded = Math.Round(value, 3, MidpointRounding.AwayFromZero);
        return rounded == 0 ? 0 : rounded;
    }

    /// <summary>Three decimals at most, invariant, never "-0".</summary>
    private static string F(float value) => Rounded(value).ToString("0.###", CultureInfo.InvariantCulture);
}
