using System.Text.Encodings.Web;
using System.Text.Json;
using System.Text.Json.Serialization;
using Avalon.Api.Contract;
using Avalon.Api.Worlds.Previews;

namespace Avalon.Exporter;

/// <summary>
/// The item wording the link preview writes and the public site's tooltip must write the same (#1189): a row for every
/// <see cref="StatType"/> member, run through <see cref="LinkPreviewText.FormatStat"/>, and attack times run through
/// <see cref="LinkPreviewText.AttackTime"/>. The server leads: the site's formatter tests against this file, and
/// <c>StatWordingShould</c> fails when the committed copy lacks a stat or the preview no longer writes a row's text,
/// so a new stat fails in both repositories until both write it.
/// </summary>
public static class StatWordingExport
{
    public const string DirectoryName = "items";
    public const string FileName = "stat-wording-v1.json";

    /// <summary>One value for every stat row: the wording, not the number, is what the rows pin.</summary>
    private const uint SampleValue = 5;

    /// <summary>
    /// A tenth of a second, a whole second, the hundredths the seeded weapons have, and two halves of a hundredth, which
    /// round up.
    /// </summary>
    private static readonly uint[] s_attackTimesMs = [2600, 2000, 784, 1005, 125];

    // camelCase like the other item files; LF on every platform; the relaxed encoder keeps "+" readable instead of
    // writing +.
    private static readonly JsonSerializerOptions s_serializerOptions = new()
    {
        WriteIndented = true,
        NewLine = "\n",
        PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
        Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping,
    };

    public static string Render()
    {
        var document = new WordingDocument(
            Comment: "Generated by tools/Avalon.Exporter -- stat-wording. Do not edit by hand. How an item's stats and a " +
                     "weapon's attack time read in the link preview (src/Server/Avalon.Api.Worlds/Previews/" +
                     "LinkPreviewText.cs) and the public site's tooltip: stat is the StatType name the REST API sends, " +
                     "id its number in item-schema-v1.json.",
            Stats: [.. Enum.GetValues<StatType>().Select(type =>
                new StatRow(type.ToString(), (int)type, SampleValue, LinkPreviewText.FormatStat(type, SampleValue)))],
            AttackTimes: [.. s_attackTimesMs.Select(ms => new AttackTimeRow(ms, LinkPreviewText.AttackTime(ms)))]);

        return JsonSerializer.Serialize(document, s_serializerOptions) + "\n";
    }

    private sealed record WordingDocument(
        [property: JsonPropertyName("$comment")] string Comment,
        List<StatRow> Stats,
        List<AttackTimeRow> AttackTimes);

    private sealed record StatRow(string Stat, int Id, uint Value, string Text);

    private sealed record AttackTimeRow(uint AttackTimeMs, string Text);
}
