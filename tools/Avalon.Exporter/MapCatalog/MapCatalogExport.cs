using System.Text.Json;
using System.Text.Json.Serialization;
using Avalon.Configuration;
using Avalon.Database.World;
using Avalon.Domain.World;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Logging.Abstractions;
using Microsoft.Extensions.Options;

namespace Avalon.Exporter;

/// <summary>
/// Exports what a client preloads for a map (maps): every creature display id the map can show, so its models load
/// behind the loading screen instead of popping in when the first one spawns. It is the superset: a map's placed
/// creatures plus everything its procedural spawn table can roll under any tag, not what one instance's seed rolled.
/// A creature only an item summons is not in it. Like doodad-catalog it reads the World database and is reviewed as a
/// data diff.
/// </summary>
public static class MapCatalogExport
{
    public const string DirectoryName = "maps";
    public const string FileName = "map-catalog-v1.json";

    private static readonly JsonSerializerOptions s_serializerOptions = new()
    {
        WriteIndented = true,
        PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
    };

    /// <summary>The same World connection string item-catalog reads, from the same sources.</summary>
    public static string? Readiness() => ItemCatalog.Readiness();

    public static void Write(string path)
    {
        string connectionString = ItemCatalog.ConnectionString()
            ?? throw new InvalidOperationException("No World connection string; readiness should have caught this.");

        IOptions<DatabaseConfiguration> options = Options.Create(new DatabaseConfiguration
        {
            World = new DatabaseConnection { ConnectionString = connectionString },
        });

        using var context = new WorldDbContext(NullLoggerFactory.Instance, options);
        string rendered = Render(
            context.CreatureTemplates.AsNoTracking().ToList(),
            context.MapCreatureSpawns.AsNoTracking().ToList(),
            context.ProceduralMapConfigs.AsNoTracking().ToList(),
            context.SpawnTables.AsNoTracking().ToList());

        Lf.Write(path, rendered);
        Console.WriteLine($"wrote {path}");
    }

    /// <summary>Pure, so the shape of the file is testable without a database.</summary>
    public static string Render(IReadOnlyCollection<CreatureTemplate> creatures,
        IReadOnlyCollection<MapCreatureSpawn> placed, IReadOnlyCollection<ProceduralMapConfig> procedural,
        IReadOnlyCollection<SpawnTable> tables)
    {
        var displayOf = creatures.ToDictionary(c => c.Id.Value, c => c.DisplayId);
        Dictionary<ushort, SortedSet<uint>> byMap = [];

        void Add(ushort map, ulong creature)
        {
            if (!displayOf.TryGetValue(creature, out uint display) || display == 0)
                return;
            if (!byMap.TryGetValue(map, out SortedSet<uint>? ids))
                byMap[map] = ids = [];
            ids.Add(display);
        }

        foreach (MapCreatureSpawn spawn in placed)
            Add(spawn.MapTemplateId.Value, spawn.CreatureTemplateId.Value);
        foreach (ProceduralMapConfig map in procedural)
        {
            SpawnTable? table = tables.FirstOrDefault(t => t.Id.Value == map.SpawnTableId.Value);
            foreach (SpawnTableEntry entry in table?.Entries ?? [])
                Add(map.MapTemplateId.Value, entry.CreatureId.Value);
        }

        var document = new CatalogDocument(
            Comment: "Generated by tools/Avalon.Exporter -- map-catalog. Do not edit by hand. creatureDisplayIds is " +
                     "every creature display id the map can show: its placed creatures and everything its spawn table " +
                     "can roll, not what one instance rolled. A creature only an item summons is not listed.",
            Maps: byMap.OrderBy(m => m.Key).Select(m => new Row(m.Key, [.. m.Value])).ToList());

        return JsonSerializer.Serialize(document, s_serializerOptions) + "\n";
    }

    private sealed record CatalogDocument(
        [property: JsonPropertyName("$comment")] string Comment,
        List<Row> Maps);

    private sealed record Row(ushort MapId, List<uint> CreatureDisplayIds);
}
