using System.Text.Json;
using System.Text.Json.Serialization;
using Avalon.Configuration;
using Avalon.Database.World;
using Avalon.Domain.World;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Logging.Abstractions;
using Microsoft.Extensions.Options;

namespace Avalon.Exporter;

/// <summary>
/// Exports the aura rows a client names and draws auras from (auras): SMSG_AURA_UPDATE and SMSG_AURA_LIST carry an aura
/// id and its timing, and a client needs the name, icon, kind, crowd control, break chances and stat modifiers to show
/// it. Like ability-catalog it reads the World database and is reviewed as a data diff. A hand-listed row: the base,
/// the scaling and the script are server-only balance. Enumerations are written as their numbers, listed in the $comment.
/// </summary>
public static class AuraCatalogExport
{
    public const string DirectoryName = "auras";
    public const string FileName = "aura-catalog-v1.json";

    private static readonly JsonSerializerOptions s_serializerOptions = new()
    {
        WriteIndented = true,
        PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
    };

    /// <summary>The same World connection string item-catalog reads, from the same sources.</summary>
    public static string? Readiness() => ItemCatalog.Readiness();

    public static void Write(string path)
    {
        string connectionString = ItemCatalog.ConnectionString()
            ?? throw new InvalidOperationException("No World connection string; readiness should have caught this.");

        IOptions<DatabaseConfiguration> options = Options.Create(new DatabaseConfiguration
        {
            World = new DatabaseConnection { ConnectionString = connectionString },
        });

        using var context = new WorldDbContext(NullLoggerFactory.Instance, options);
        var auras = context.AuraTemplates.AsNoTracking().Include(a => a.Modifiers).ToList();

        Lf.Write(path, Render(auras));
        Console.WriteLine($"wrote {path} ({auras.Count} aura templates)");
    }

    /// <summary>Pure, so the shape of the file is testable without a database.</summary>
    public static string Render(IReadOnlyCollection<AuraTemplate> auras)
    {
        var document = new CatalogDocument(
            Comment: "Generated by tools/Avalon.Exporter -- aura-catalog. Do not edit by hand. kind: 1 helpful, 2 harmful. " +
                     "periodicKind: 0 none, 1 damage, 2 heal. stacking: 1 refresh, 2 stack (up to maxStacks), 3 one per " +
                     "caster. Modifiers: stat 1 armor, 4 crit %, 5 evasion, 6 block %, 8 movement speed %, 9 max health, " +
                     "10 max power, 11 fire resistance, 12 cold resistance, 13 lightning resistance, 14 blight resistance, " +
                     "15 max ward, 16 increased damage %, 17 increased physical damage %, 18 increased fire damage %, " +
                     "19 increased cold damage %, 20 increased lightning damage %, 21 increased blight damage %, " +
                     "22 increased attack damage %, 23 increased spell damage %, 24 increased area damage %, " +
                     "25 increased projectile damage %, 26 increased melee damage %, 27 increased damage over time %, " +
                     "28 increased healing %, 29 crit multiplier (points: 50 makes a 1.5 crit 2.0), 30 attack speed %, " +
                     "31 cast speed %, 32 cooldown recovery % (2, 3 and 7 are retired, never reused); kind 1 flat (adds " +
                     "the value), 2 increased (joins the stat's sum of increases), 3 more (multiplies on its own); an " +
                     "increased stat (16-28) takes flat or more, never increased; each times the stacks held. What a " +
                     "periodic aura deals or heals (its periodicBase and periodicEffectiveness, the percent of its source's " +
                     "base roll it adds) is the server's: the amounts arrive on the wire. " +
                     "durationMs and tickIntervalMs in milliseconds; 0 ticks never. control: flags, 1 stun, 2 root, " +
                     "4 silence, 0 none (a slow, a harmful aura with a negative movement speed modifier, is never a flag in " +
                     "this file; aura entries on the wire add 8 for it); " +
                     "breakOnDamagePct: percent chance it ends each time its holder takes damage; breakPerSecondPct: " +
                     "percent chance it ends on its own, once per second held. The server sends the control on the wire " +
                     "too: trust that over this file.",
            Auras: auras.OrderBy(a => a.Id.Value).Select(Row.From).ToList());

        return JsonSerializer.Serialize(document, s_serializerOptions) + "\n";
    }

    private sealed record CatalogDocument(
        [property: JsonPropertyName("$comment")] string Comment,
        List<Row> Auras);

    private sealed record Modifier(byte Stat, byte Kind, float Value);

    private sealed record Row(
        uint Id, string Name, string Icon, byte Kind, uint DurationMs, uint TickIntervalMs, byte PeriodicKind,
        byte Stacking, uint MaxStacks, byte Control, float BreakOnDamagePct, float BreakPerSecondPct,
        List<Modifier> Modifiers)
    {
        public static Row From(AuraTemplate t) => new(
            t.Id.Value, t.Name ?? string.Empty, t.Icon ?? string.Empty, (byte)t.Kind, t.DurationMs, t.TickIntervalMs,
            (byte)t.PeriodicKind, (byte)t.Stacking, t.MaxStacks, (byte)t.Control, t.BreakOnDamagePct,
            t.BreakPerSecondPct,
            t.Modifiers.OrderBy(m => m.Stat).Select(m => new Modifier((byte)m.Stat, (byte)m.Kind, m.Value)).ToList());
    }
}
