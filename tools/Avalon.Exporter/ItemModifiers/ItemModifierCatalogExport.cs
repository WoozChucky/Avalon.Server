using System.Globalization;
using System.Text.Json;
using System.Text.Json.Serialization;
using Avalon.Database.World.Seeding;
using Avalon.Domain.World;
using Avalon.World.Combat;

namespace Avalon.Exporter;

/// <summary>
/// Exports the modifier catalog the client vendors (#1179), from <see cref="ItemModifierSeed" /> and
/// <see cref="ResonanceSeed" />, so it needs no database: the Resonance themes (#1180: id, name and each theme's effects,
/// by count), the groups (id, kind, code, element, name, theme id), the modifiers (id, group id, tier, stat lines) and
/// each template's linked modifier ids, so a client can name an item's modifiers, show their tiers and tell a base's
/// implicit and a unique's own modifier apart from its rolled affixes. Enumerations are written as their numbers, listed
/// in the $comment.
/// </summary>
public static class ItemModifierCatalogExport
{
    public const string DirectoryName = "items";
    public const string FileName = "item-modifier-catalog-v1.json";

    private static readonly JsonSerializerOptions s_serializerOptions = new()
    {
        WriteIndented = true,
        NewLine = "\n",
        PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
    };

    public static void Write(string path)
    {
        string json = Render();
        Lf.Write(path, json);
        Console.WriteLine($"wrote {path} ({ItemModifierSeed.Modifiers().Length} item modifiers)");
    }

    /// <summary>Pure: the file's whole content.</summary>
    public static string Render()
    {
        ILookup<int, ItemModifierStat> stats = ItemModifierSeed.Stats().ToLookup(s => s.ModifierId);
        ILookup<int, ItemThemeEffect> effects = ResonanceSeed.Effects().ToLookup(e => e.ThemeId);
        string radius = ResonanceDispatcher.ChainRadiusMetres.ToString(CultureInfo.InvariantCulture);

        var document = new CatalogDocument(
            Comment: "Generated by tools/Avalon.Exporter -- item-modifier-catalog, from the seed. Do not edit by hand. " +
                     "kind: 1 prefix, 2 suffix, 3 unique, 4 implicit. element (a family split by element): 0 physical, " +
                     "1 fire, 2 cold, 3 lightning, 4 blight. tier: 1-9 on a prefix, suffix or implicit, counting down (9 the " +
                     "weakest), null on a unique. stat: the StatType numbers of item-schema-v1.json; min2 and max2 " +
                     "are the high end of an \"adds X to Y\" line, null on every other. templates: the modifiers every " +
                     "copy of a template rolls when it is made, in order: a base's implicit at its tier, a unique's own " +
                     "modifier (a unique's copy rolls its base's implicit first: baseTemplateId in item-catalog-v1.json). " +
                     "themeId: the Resonance theme of a prefix or suffix group (themes), null on a unique or implicit group. " +
                     "effects: a theme's Resonance effects by count; the highest count a theme reaches runs its rows. " +
                     "trigger: 1 hit, 2 crit, 3 kill, 4 struck, 5 evaded, 6 ward broken. target: 1 wearer, 2 hit target, " +
                     $"3 attacker. auraId: aura-catalog-v1.json. chainTargets: further creatures within {radius} m. " +
                     "atOrBelowLifePct: the wearer's life, in percent, at or below which it fires, null for any. " +
                     "damageType: 0 physical to 4 blight, null on an effect that deals no damage.",
            Themes:
            [
                .. ItemModifierSeed.Themes().Select(t => new ThemeRow(t.Id, t.Name,
                    [
                        .. effects[t.Id].OrderBy(e => e.Id).Select(e => new EffectRow(e.Id, e.Count, (int)e.Trigger, e.ChancePct,
                            e.CooldownMs, e.AuraId.Value, (int)e.Target, e.ChainTargets, e.AtOrBelowLifePct, (int?)e.DamageType)),
                    ])),
            ],
            Groups: [.. ItemModifierSeed.Groups().Select(g => new GroupRow(g.Id, (int)g.Kind, g.Code, (int?)g.Element, g.Name, g.ThemeId))],
            Modifiers:
            [
                .. ItemModifierSeed.Modifiers().Select(m => new ModifierRow(m.Id, m.GroupId, m.Tier,
                    [.. stats[m.Id].OrderBy(s => s.Index).Select(s => new StatRow(s.Index, (int)s.Stat, s.Min, s.Max, s.Min2, s.Max2))])),
            ],
            Templates:
            [
                .. ItemModifierSeed.TemplateLinks()
                    .GroupBy(l => l.TemplateId.Value)
                    .OrderBy(g => g.Key)
                    .Select(g => new TemplateRow(g.Key, [.. g.OrderBy(l => l.Index).Select(l => l.ModifierId)])),
            ]);

        return JsonSerializer.Serialize(document, s_serializerOptions) + "\n";
    }

    private sealed record CatalogDocument(
        [property: JsonPropertyName("$comment")] string Comment,
        IReadOnlyList<ThemeRow> Themes,
        IReadOnlyList<GroupRow> Groups,
        IReadOnlyList<ModifierRow> Modifiers,
        IReadOnlyList<TemplateRow> Templates);

    private sealed record ThemeRow(int Id, string Name, IReadOnlyList<EffectRow> Effects);

    private sealed record EffectRow(int Id, int Count, int Trigger, float ChancePct, uint CooldownMs, uint AuraId, int Target,
        int ChainTargets, float? AtOrBelowLifePct, int? DamageType);

    private sealed record GroupRow(int Id, int Kind, string? Code, int? Element, string Name, int? ThemeId);

    private sealed record ModifierRow(int Id, int GroupId, byte? Tier, IReadOnlyList<StatRow> Stats);

    private sealed record StatRow(byte Index, int Stat, int Min, int Max, int? Min2, int? Max2);

    private sealed record TemplateRow(ulong TemplateId, IReadOnlyList<int> ModifierIds);
}
