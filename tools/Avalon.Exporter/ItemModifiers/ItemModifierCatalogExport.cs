using System.Text.Json;
using System.Text.Json.Serialization;
using Avalon.Database.World.Seeding;
using Avalon.Domain.World;

namespace Avalon.Exporter;

/// <summary>
/// Exports the modifier catalog the client vendors (#1179), from <see cref="ItemModifierSeed" />, so it needs no database:
/// the groups (id, kind, code, element, name), the modifiers (id, group id, tier, stat lines) and each template's linked
/// modifier ids, so a client can name an item's modifiers, show their tiers and tell a base's implicits and a unique's
/// own modifier apart from its rolled affixes. Enumerations are written as their numbers, listed in the $comment.
/// </summary>
public static class ItemModifierCatalogExport
{
    public const string DirectoryName = "items";
    public const string FileName = "item-modifier-catalog-v1.json";

    private static readonly JsonSerializerOptions s_serializerOptions = new()
    {
        WriteIndented = true,
        NewLine = "\n",
        PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
    };

    public static void Write(string path)
    {
        string json = Render();
        Lf.Write(path, json);
        Console.WriteLine($"wrote {path} ({ItemModifierSeed.Modifiers().Length} item modifiers)");
    }

    /// <summary>Pure: the file's whole content.</summary>
    public static string Render()
    {
        ILookup<int, ItemModifierStat> stats = ItemModifierSeed.Stats().ToLookup(s => s.ModifierId);

        var document = new CatalogDocument(
            Comment: "Generated by tools/Avalon.Exporter -- item-modifier-catalog, from the seed. Do not edit by hand. " +
                     "kind: 1 prefix, 2 suffix, 3 unique, 4 implicit. element (a family split by element): 0 physical, " +
                     "1 fire, 2 cold, 3 lightning, 4 blight. tier: 1-5 on a prefix or suffix, null on a unique or an " +
                     "implicit. stat: the StatType numbers of item-schema-v1.json; min2 and max2 are the high end of an " +
                     "\"adds X to Y\" line, null on every other. templates: the modifiers every copy of a template rolls " +
                     "when it is made, in order.",
            Groups: [.. ItemModifierSeed.Groups().Select(g => new GroupRow(g.Id, (int)g.Kind, g.Code, (int?)g.Element, g.Name))],
            Modifiers:
            [
                .. ItemModifierSeed.Modifiers().Select(m => new ModifierRow(m.Id, m.GroupId, m.Tier,
                    [.. stats[m.Id].OrderBy(s => s.Index).Select(s => new StatRow(s.Index, (int)s.Stat, s.Min, s.Max, s.Min2, s.Max2))])),
            ],
            Templates:
            [
                .. ItemModifierSeed.TemplateLinks()
                    .GroupBy(l => l.TemplateId.Value)
                    .OrderBy(g => g.Key)
                    .Select(g => new TemplateRow(g.Key, [.. g.OrderBy(l => l.Index).Select(l => l.ModifierId)])),
            ]);

        return JsonSerializer.Serialize(document, s_serializerOptions) + "\n";
    }

    private sealed record CatalogDocument(
        [property: JsonPropertyName("$comment")] string Comment,
        IReadOnlyList<GroupRow> Groups,
        IReadOnlyList<ModifierRow> Modifiers,
        IReadOnlyList<TemplateRow> Templates);

    private sealed record GroupRow(int Id, int Kind, string? Code, int? Element, string Name);

    private sealed record ModifierRow(int Id, int GroupId, byte? Tier, IReadOnlyList<StatRow> Stats);

    private sealed record StatRow(byte Index, int Stat, int Min, int Max, int? Min2, int? Max2);

    private sealed record TemplateRow(ulong TemplateId, IReadOnlyList<int> ModifierIds);
}
