using System.Text.Json;
using System.Text.Json.Serialization;
using Avalon.Database.World.Seeding;
using Avalon.Domain.World;

namespace Avalon.Exporter;

/// <summary>
/// Exports the shared talent tree the client vendors (#1181), from <see cref="TalentSeed" />, so it needs no database:
/// every node (kind, name, place on the wheel, fork, linked ability, keystone rule, stat lines, a capstone's modifiers),
/// every edge once, the fork groups and the node each class starts on. Enumerations are written as their numbers, listed
/// in the $comment.
/// </summary>
public static class TalentCatalogExport
{
    public const string DirectoryName = "talents";
    public const string FileName = "talent-catalog-v1.json";

    private static readonly JsonSerializerOptions s_serializerOptions = new()
    {
        WriteIndented = true,
        NewLine = "\n",
        PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
    };

    public static void Write(string path)
    {
        string json = Render();
        Lf.Write(path, json);
        Console.WriteLine($"wrote {path} ({TalentSeed.Nodes().Length} talent nodes)");
    }

    /// <summary>Pure: the file's whole content.</summary>
    public static string Render()
    {
        TalentTreeRows rows = TalentSeed.Rows();
        ILookup<int, TalentNodeStat> stats = rows.Stats.ToLookup(s => s.NodeId);
        var abilities = rows.Abilities.ToDictionary(a => a.NodeId, a => a.AbilityId.Value);
        ILookup<int, TalentAbilityModifier> modifiers = rows.Modifiers.ToLookup(m => m.NodeId);

        var document = new CatalogDocument(
            Comment: "Generated by tools/Avalon.Exporter -- talent-catalog, from the seed. Do not edit by hand. " +
                     "Ids are surrogates that mean nothing; a character's saved talents name them. " +
                     "kind: 1 start, 2 small, 3 notable, 4 ability, 5 capstone, 6 keystone, 7 junction. " +
                     "name: set on a start, a notable, an ability, a capstone and a keystone, null on every other. " +
                     "angle: degrees in (-180, 180]; radius: layout units. forkGroupId: the capstone fork (forkGroups) " +
                     "of which a character holds one node at most, null on every other node. abilityId: the ability a " +
                     "start or an ability node grants (ability-catalog-v1.json), null on every other node. " +
                     "keystone: the rule a keystone bends, 1 life cost (abilities cost life instead of mana), " +
                     "2 no crits, 3 ward takes all (the ward also absorbs blight and bleeding, and waits twice as " +
                     "long to recharge); null on every other node and on a keystone of stat lines only. " +
                     "stat: the StatType numbers of item-schema-v1.json; kind: 1 added (summed with the gear's lines), " +
                     "2 more (a multiplier of its own); valueMax: the high end of an \"adds X to Y\" line, null on every " +
                     "other. modifiers: how a capstone reshapes the ability its branch hangs from (abilityId), by kind: " +
                     "1 added projectiles (value more, in a fan 10 degrees apart), 2 impact explosion (radius value / 10 " +
                     "metres, value2 % effectiveness), 3 area % (a circle's radius, and an explosion's), 4 cone reach %, " +
                     "5 cone arc % (at most 360 degrees), 6 aura stacks (value more), 7 aura duration %, 8 second hit " +
                     "(value % effectiveness); value2 is set on an impact explosion only, null on every other kind; " +
                     "empty on every node but a capstone. edges: undirected, each once with the smaller id first. " +
                     "class: 1 warrior, 2 wizard, 3 hunter, 4 cleric.",
            Nodes:
            [
                .. rows.Nodes.OrderBy(n => n.Id).Select(n => new NodeRow(n.Id, (int)n.Kind, n.Name, n.Angle, n.Radius,
                    n.ForkGroupId, abilities.TryGetValue(n.Id, out uint ability) ? ability : null, (int?)n.Keystone,
                    [
                        .. stats[n.Id].OrderBy(s => s.Stat).ThenBy(s => s.Kind)
                            .Select(s => new StatRow((int)s.Stat, (int)s.Kind, s.Value, s.ValueMax)),
                    ],
                    [
                        .. modifiers[n.Id].OrderBy(m => m.Kind)
                            .Select(m => new ModifierRow((int)m.Kind, m.AbilityId.Value, m.Value, m.Value2)),
                    ])),
            ],
            Edges: [.. rows.Edges.OrderBy(e => e.NodeA).ThenBy(e => e.NodeB).Select(e => new EdgeRow(e.NodeA, e.NodeB))],
            ForkGroups: [.. rows.ForkGroups.OrderBy(g => g.Id).Select(g => new ForkGroupRow(g.Id))],
            ClassStarts: [.. rows.Starts.OrderBy(s => s.Class).Select(s => new ClassStartRow((int)s.Class, s.NodeId))]);

        return JsonSerializer.Serialize(document, s_serializerOptions) + "\n";
    }

    private sealed record CatalogDocument(
        [property: JsonPropertyName("$comment")] string Comment,
        IReadOnlyList<NodeRow> Nodes,
        IReadOnlyList<EdgeRow> Edges,
        IReadOnlyList<ForkGroupRow> ForkGroups,
        IReadOnlyList<ClassStartRow> ClassStarts);

    private sealed record NodeRow(int Id, int Kind, string? Name, float Angle, float Radius, int? ForkGroupId, uint? AbilityId,
        int? Keystone, IReadOnlyList<StatRow> Stats, IReadOnlyList<ModifierRow> Modifiers);

    private sealed record StatRow(int Stat, int Kind, int Value, int? ValueMax);

    private sealed record ModifierRow(int Kind, uint AbilityId, int Value, int? Value2);

    private sealed record EdgeRow(int A, int B);

    private sealed record ForkGroupRow(int Id);

    private sealed record ClassStartRow(int Class, int NodeId);
}
